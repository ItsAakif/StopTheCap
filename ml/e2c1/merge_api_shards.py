def _summary(result: MergeResult, *, mode: str) -> dict[str, Any]:
    return {
        "mode": mode,
        "generators": list(GENERATOR_IDS),
        "merged_rows": len(result.records),
        "merged_sha256": result.merged_sha256,
        "counts": {
            "by_generator": result.report["counts"]["by_generator"],
            "by_partition": result.report["counts"]["by_partition"],
            "by_decoding": result.report["counts"]["by_decoding"],
            "by_topic": result.report["counts"]["by_topic"],
        },
        "dropped_invalid_rows": result.report["dropped_invalid_rows"]["count"],
        "dropped_distinct_prompt_ids": result.report["dropped_invalid_rows"][
            "distinct_prompt_ids"
        ],
        "duplicates": result.report["duplicates"]["count"],
        "failures_found": result.report["failures_found"]["count"],
        "reconciliation": result.report["reconciliation"],
        "split_digest": result.split_digest,
        "prompt_manifest_sha256": result.prompt_manifest_sha256,
    }


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="ml.e2c1.merge_api_shards",
        description=(
            "Merge the frozen E2-C1 API generation shards, update the registry/"
            "manifests and run decontamination."
        ),
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="validate and print the composition without writing anything",
    )
    parser.add_argument(
        "--shards-root", type=Path, default=DEFAULT_SHARDS_ROOT
    )
    parser.add_argument("--prompts", type=Path, default=DEFAULT_PROMPTS_PATH)
    parser.add_argument("--splits", type=Path, default=DEFAULT_SPLITS_PATH)
    parser.add_argument("--licences", type=Path, default=DEFAULT_LICENCES_PATH)
    parser.add_argument("--corpus", type=Path, default=DEFAULT_CORPUS_PATH)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = parser.parse_args(argv)

    result = merge_corpus(
        shards_root=args.shards_root,
        prompts_path=args.prompts,
        splits_path=args.splits,
        expected_split_digest=EXPECTED_SPLIT_DIGEST,
        expected_prompt_manifest_sha256=EXPECTED_PROMPT_MANIFEST_SHA256,
    )

    if args.dry_run:
        print(json.dumps(_summary(result, mode="dry-run"), indent=2, sort_keys=True))
        return 0

    out_dir = Path(args.out_dir)
    merged_path = out_dir / "merged.jsonl"
    merged_sha = write_merged(merged_path, result)
    report = dict(result.report)
    report["merged"] = {
        "path": str(merged_path),
        "rows": len(result.records),
        "sha256": merged_sha,
        "bytes": len(result.merged_bytes),
    }
    write_json(out_dir / "merge_report.json", report)

    existing_registry = json.loads(
        _read_bytes(args.licences).decode("utf-8")
    )
    write_json(args.licences, build_licence_registry(existing_registry))

    updated_split = build_split_counts(result.split, result.records)
    if e2c1_split_digest(
        {str(key): str(value) for key, value in updated_split["assignments"].items()},
        str(updated_split["salt"]),
    ) != EXPECTED_SPLIT_DIGEST:
        raise MergeError("split digest changed while updating counts")
    write_json(args.splits, updated_split)

    corpus = build_corpus_manifest(
        result,
        merged_path=merged_path,
        prompt_manifest_path=Path(args.prompts),
        split_manifest_path=Path(args.splits),
    )
    write_json(args.corpus, corpus)

    decontamination = run_decontamination(
        result.records,
        merged_path=merged_path,
        merged_sha256=merged_sha,
        out_dir=out_dir,
    )

    summary = _summary(result, mode="full")
    summary["decontamination"] = {
        "records_examined": decontamination["records_examined"],
        "removed_exact": decontamination["removed_exact"],
        "removed_near": decontamination["removed_near"],
        "removed_total": decontamination["removed_total"],
        "removed_by_reference": decontamination["removed_by_reference"],
        "reference_size": decontamination["reference_size"],
    }
    summary["outputs"] = [
        str(merged_path),
        str(out_dir / "merge_report.json"),
        str(args.licences),
        str(args.splits),
        str(args.corpus),
        str(out_dir / "decontamination.json"),
        str(out_dir / "decontaminated_ids.json"),
    ]
    print(json.dumps(summary, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
