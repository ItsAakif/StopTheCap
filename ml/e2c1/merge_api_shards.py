def run_decontamination(
    records: Sequence[Mapping[str, Any]],
    *,
    merged_path: Path,
    merged_sha256: str,
    out_dir: Path,
    examples_limit: int = 25,
) -> dict[str, Any]:
    """Scan every merged ``generated_text`` against the full reference set.

    Rows are never deleted.  The returned report and ``decontaminated_ids.json``
    list the sample ids that a training gate must exclude.
    """
    from ml.data.decontaminate import (  # noqa: PLC0415 -- heavy optional import
        _hc3_full_items,
        _reference_items,
        build_reference_index,
        classify,
    )

    canonical_references = list(_reference_items(("ghostbuster", "raid", "hc3")))
    hc3_references = _hc3_full_items()
    references = canonical_references + hc3_references
    index = build_reference_index(references)

    removed_reasons: collections.Counter[str] = collections.Counter()
    removed_by_reference: collections.Counter[str] = collections.Counter()
    removed_by_label: collections.Counter[str] = collections.Counter()
    examples: list[dict[str, Any]] = []
    excluded: list[str] = []
    examined = 0

    for record in records:
        text = str(record.get("generated_text") or "")
        reason, matched, jaccard = classify(text, index)
        examined += 1
        if reason is None:
            continue
        removed_reasons[reason] += 1
        if matched:
            removed_by_reference[str(matched).split(":")[0]] += 1
            removed_by_label[str(matched)] += 1
        excluded.append(str(record["sample_id"]))
        if len(examples) < examples_limit:
            examples.append(
                {
                    "sample_id": record["sample_id"],
                    "generator_id": record.get("generator_id"),
                    "reason": reason,
                    "matched": matched,
                    "jaccard": jaccard,
                    "preview": text[:120],
                }
            )

    removed_total = sum(removed_reasons.values())
    report = {
        "schema_version": "1.0",
        "generated_at": _now_iso(),
        "merged_path": str(merged_path),
        "merged_sha256": merged_sha256,
        "records_examined": examined,
        "removed_exact": removed_reasons.get("exact", 0),
        "removed_near": removed_reasons.get("near", 0),
        "removed_empty": removed_reasons.get("empty", 0),
        "removed_total": removed_total,
        "removal_rate": round(removed_total / examined, 6) if examined else None,
        "removed_by_reason": dict(sorted(removed_reasons.items())),
        "removed_by_reference": dict(sorted(removed_by_reference.items())),
        "removed_by_label": dict(sorted(removed_by_label.items())),
        "reference_size": index.size,
        "references": {
            "canonical": len(canonical_references),
            "hc3_full": len(hc3_references),
            "total": len(references),
        },
        "thresholds": {
            "near_dup_jaccard": 0.85,
            "shingle_k": 5,
        },
        "examples": examples,
        "excluded_ids": sorted(excluded),
    }

    out_dir = Path(out_dir)
    write_json(out_dir / "decontamination.json", report)
    write_json(
        out_dir / "decontaminated_ids.json",
        {
            "schema_version": "1.0",
            "merged_sha256": merged_sha256,
            "n_excluded": len(excluded),
            "excluded_ids": sorted(excluded),
            "by_reason": dict(sorted(removed_reasons.items())),
            "by_reference": dict(sorted(removed_by_reference.items())),
        },
    )
    return report


