def model_revision_for(model_as_served: str, date: str = GENERATOR_DATE) -> str:
    """Frozen per-provider revision: ``sha256(model_as_served|date)[:40]``."""
    return hashlib.sha256(
        f"{model_as_served}|{date}".encode("utf-8")
    ).hexdigest()[:40]


def api_chat_template_sha256() -> str:
    """SHA-256 of the exact API system + user template."""
    return hashlib.sha256(
        (SYSTEM + "\n" + USER_TEMPLATE).encode("utf-8")
    ).hexdigest()


def config_digest_for(generator_ids: Sequence[str]) -> str:
    """Canonical digest for the API generation config."""
    payload = {
        "config_id": CONFIG_ID,
        "generators": list(generator_ids),
        "max_new_tokens": MAX_NEW_TOKENS,
        "prompt_template_id": PROMPT_TEMPLATE_ID,
    }
    return hashlib.sha256(canonical_json(payload).encode("utf-8")).hexdigest()


