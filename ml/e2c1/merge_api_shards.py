@dataclass
class MergeResult:
    records: list[dict[str, Any]]
    report: dict[str, Any]
    prompts: dict[str, dict]
    prompt_manifest_sha256: str
    split: dict[str, Any]
    split_digest: str
    merged_bytes: bytes

    @property
    def merged_sha256(self) -> str:
        return hashlib.sha256(self.merged_bytes).hexdigest()


def _selected_specs(generator_ids: Sequence[str] | None) -> list[GeneratorSpec]:
    if generator_ids is None:
        return list(GENERATORS)
    wanted = list(generator_ids)
    unknown = sorted(set(wanted) - set(GENERATOR_BY_ID))
    if unknown:
        raise MergeError(f"unknown generator ids: {unknown}")
    return [GENERATOR_BY_ID[generator_id] for generator_id in wanted]


def serialise_records(records: Sequence[Mapping[str, Any]]) -> bytes:
    """Canonical JSONL bytes, one sorted-key object per line."""
    return b"".join(
        json.dumps(
            dict(record),
            sort_keys=True,
            separators=(",", ":"),
            ensure_ascii=False,
        ).encode("utf-8")
        + b"\n"
        for record in records
    )


def _nested_matrix(
    specs: Sequence[GeneratorSpec],
    partitions: Sequence[str],
    decodings: Sequence[str],
    topics: Sequence[str],
) -> dict[str, dict[str, dict[str, dict[str, int]]]]:
    return {
        spec.generator_id: {
            partition: {
                decoding: {topic: 0 for topic in topics}
                for decoding in decodings
            }
            for partition in partitions
        }
        for spec in specs
    }


def _merge_counts(
    records: Sequence[Mapping[str, Any]],
    specs: Sequence[GeneratorSpec],
    partitions: Sequence[str],
    decodings: Sequence[str],
    topics: Sequence[str],
) -> dict[str, Any]:
    generator_ids = [spec.generator_id for spec in specs]
    by_generator = {generator_id: 0 for generator_id in generator_ids}
    by_partition = {partition: 0 for partition in partitions}
    by_decoding = {decoding: 0 for decoding in decodings}
    by_topic = {topic: 0 for topic in topics}
    by_generator_partition = {
        generator_id: {partition: 0 for partition in partitions}
        for generator_id in generator_ids
    }
    by_generator_decoding = {
        generator_id: {decoding: 0 for decoding in decodings}
        for generator_id in generator_ids
    }
    by_partition_decoding = {
        partition: {decoding: 0 for decoding in decodings}
        for partition in partitions
    }
    by_generator_partition_decoding = {
        generator_id: {
            partition: {decoding: 0 for decoding in decodings}
            for partition in partitions
        }
        for generator_id in generator_ids
    }
    by_generator_partition_decoding_topic = _nested_matrix(
        specs, partitions, decodings, topics
    )

    for record in records:
        generator_id = str(record["generator_id"])
        partition = str(record["partition"])
        decoding = str(record["decoding_config_id"])
        topic = str(record["topic_category"])
        by_generator[generator_id] += 1
        by_partition[partition] += 1
        by_decoding[decoding] += 1
        by_topic[topic] += 1
        by_generator_partition[generator_id][partition] += 1
        by_generator_decoding[generator_id][decoding] += 1
        by_partition_decoding[partition][decoding] += 1
        by_generator_partition_decoding[generator_id][partition][decoding] += 1
        by_generator_partition_decoding_topic[generator_id][partition][decoding][
            topic
        ] += 1

    return {
        "by_generator": by_generator,
        "by_partition": by_partition,
        "by_decoding": by_decoding,
        "by_topic": by_topic,
        "by_generator_partition": by_generator_partition,
        "by_generator_decoding": by_generator_decoding,
        "by_partition_decoding": by_partition_decoding,
        "by_generator_partition_decoding": by_generator_partition_decoding,
        "by_generator_partition_decoding_topic": (
            by_generator_partition_decoding_topic
        ),
    }


def merge_corpus(
    *,
    shards_root: Path | str = DEFAULT_SHARDS_ROOT,
    prompts_path: Path | str = DEFAULT_PROMPTS_PATH,
    splits_path: Path | str = DEFAULT_SPLITS_PATH,
    generator_ids: Sequence[str] | None = None,
    expected_split_digest: str | None = None,
    expected_prompt_manifest_sha256: str | None = None,
) -> MergeResult:
    """Load, validate and merge the frozen shards without writing anything."""
    shards_root = Path(shards_root)
    prompts, prompt_sha = load_prompt_manifest(Path(prompts_path))
    if (
        expected_prompt_manifest_sha256 is not None
        and prompt_sha != expected_prompt_manifest_sha256
    ):
        raise MergeError(
            f"prompt manifest sha256 {prompt_sha!r} != "
            f"expected {expected_prompt_manifest_sha256!r}"
        )

    split, split_digest = load_split_manifest(Path(splits_path))
    if expected_split_digest is not None and split_digest != expected_split_digest:
        raise MergeError(
            f"split digest {split_digest!r} != expected {expected_split_digest!r}"
        )
    declared_prompt_sha = split.get("prompt_manifest_sha256")
    if declared_prompt_sha is not None and declared_prompt_sha != prompt_sha:
        raise MergeError(
            f"split prompt_manifest_sha256 {declared_prompt_sha!r} != "
            f"prompt manifest sha256 {prompt_sha!r}"
        )
    assignments = {
        str(key): str(value)
        for key, value in split["assignments"].items()
    }

    specs = _selected_specs(generator_ids)
    config_digest = config_digest_for(GENERATOR_IDS)
    chat_sha = DEFAULT_CHAT_TEMPLATE_SHA256

    shard_files: dict[str, list[str]] = {}
    failure_files: list[Path] = []
    successes = 0
    dropped: list[LoadedRow] = []
    duplicates: list[dict[str, Any]] = []
    records: list[dict[str, Any]] = []
    seen: set[tuple[str, str, str]] = set()

    for spec in specs:
        files, rows = load_generator_rows(shards_root, spec)
        shard_files[spec.generator_id] = [str(path) for path in files]
        failure_files.extend(failure_files_for(files))
        successes += len(rows)

        for row in rows:
            if row.prompt_id not in prompts:
                dropped.append(row)
                continue
            if row.prompt_id not in assignments:
                raise MergeError(
                    f"{row.path}:{row.line_number}: prompt {row.prompt_id} has "
                    "no split assignment"
                )
            key = (spec.generator_id, row.prompt_id, row.decoding_config_id)
            if key in seen:
                duplicates.append(
                    {
                        **row.as_report(),
                        "generator_id": spec.generator_id,
                    }
                )
                continue
            seen.add(key)
            record = build_record(
                spec,
                row,
                prompts[row.prompt_id],
                assignments[row.prompt_id],
                config_digest=config_digest,
                chat_template_sha256=chat_sha,
            )
            records.append(record.model_dump(mode="json"))

    records.sort(key=lambda record: str(record["sample_id"]))
    sample_ids = [str(record["sample_id"]) for record in records]
    if len(set(sample_ids)) != len(sample_ids):
        raise MergeError("merged corpus contains duplicate sample_ids")

    merged_bytes = serialise_records(records)
    counts = _merge_counts(
        records, list(GENERATORS), list(PARTITIONS), list(DECODING_IDS),
        list(TOPIC_TAXONOMY),
    )
    dropped_by_prompt: collections.Counter[str] = collections.Counter(
        row.prompt_id for row in dropped
    )
    failures = scan_failure_files(sorted(set(failure_files)))

    report = {
        "schema_version": "1.0",
        "config_id": CONFIG_ID,
        "prompt_template_id": PROMPT_TEMPLATE_ID,
        "generated_at": _now_iso(),
        "generators": {
            spec.generator_id: {
                "model_id": spec.model_id,
                "model_as_served": spec.model_as_served,
                "model_revision": spec.model_revision,
            }
            for spec in GENERATORS
        },
        "input": {
            "shards_root": str(shards_root),
            "prompts": str(prompts_path),
            "splits": str(splits_path),
            "shards": shard_files,
            "failure_files": [str(path) for path in sorted(set(failure_files))],
            "successes": successes,
        },
        "counts": counts,
        "dropped_invalid_rows": {
            "count": len(dropped),
            "distinct_prompt_ids": len(dropped_by_prompt),
            "by_prompt_id": dict(sorted(dropped_by_prompt.items())),
            "rows": [row.as_report() for row in dropped],
        },
        "duplicates": {
            "count": len(duplicates),
            "rows": duplicates,
        },
        "failures_found": failures,
        "reconciliation": {
            "successes": successes,
            "merged": len(records),
            "dropped_invalid": len(dropped),
            "duplicates": len(duplicates),
            "reconciled": successes
            == len(records) + len(dropped) + len(duplicates),
        },
        "merged": {
            "rows": len(records),
            "sha256": hashlib.sha256(merged_bytes).hexdigest(),
            "bytes": len(merged_bytes),
        },
    }
    return MergeResult(
        records=records,
        report=report,
        prompts=prompts,
        prompt_manifest_sha256=prompt_sha,
        split=split,
        split_digest=split_digest,
        merged_bytes=merged_bytes,
    )


