def build_split_counts(
    split: Mapping[str, Any], records: Sequence[Mapping[str, Any]]
) -> dict[str, Any]:
    """Return a copy of ``split`` whose generation counts describe the corpus.

    ``assignments``, ``salt`` and ``split_digest`` are left byte-for-byte
    identical; only the generator/decoding matrices change.  ``by_partition`` and
    ``by_partition_topic`` remain prompt-level counts because the split is a
    prompt split.
    """
    updated = copy.deepcopy(dict(split))
    counts = updated.setdefault("counts", {})
    matrix = _nested_matrix(
        list(GENERATORS), list(PARTITIONS), list(DECODING_IDS),
        list(TOPIC_TAXONOMY),
    )
    for record in records:
        matrix[str(record["generator_id"])][str(record["partition"])][
            str(record["decoding_config_id"])
        ][str(record["topic_category"])] += 1

    by_gd: dict[str, dict[str, dict[str, int]]] = {
        partition: {
            spec.generator_id: {decoding: 0 for decoding in DECODING_IDS}
            for spec in GENERATORS
        }
        for partition in PARTITIONS
    }
    for spec in GENERATORS:
        for partition in PARTITIONS:
            for decoding in DECODING_IDS:
                by_gd[partition][spec.generator_id][decoding] = sum(
                    matrix[spec.generator_id][partition][decoding].values()
                )

    counts["by_partition_generator_decoding"] = by_gd
    counts["by_partition_generator_decoding_topic"] = {
        partition: {
            spec.generator_id: {
                decoding: dict(
                    matrix[spec.generator_id][partition][decoding]
                )
                for decoding in DECODING_IDS
            }
            for spec in GENERATORS
        }
        for partition in PARTITIONS
    }
    updated["counts"] = counts
    return updated


def _coverage(
    records: Sequence[Mapping[str, Any]], prompts: Mapping[str, Any]
) -> dict[str, Any]:
    prompt_generators: dict[str, set[str]] = collections.defaultdict(set)
    for record in records:
        prompt_generators[str(record["prompt_id"])].add(
            str(record["generator_id"])
        )
    histogram = collections.Counter(
        len(generators) for generators in prompt_generators.values()
    )
    return {
        "prompts_in_manifest": len(prompts),
        "prompts_with_samples": len(prompt_generators),
        "prompts_with_1_generator": histogram.get(1, 0),
        "prompts_with_2_generators": histogram.get(2, 0),
        "prompts_with_3_generators": histogram.get(3, 0),
        "histogram": {
            "1": histogram.get(1, 0),
            "2": histogram.get(2, 0),
            "3": histogram.get(3, 0),
        },
    }


def build_corpus_manifest(
    result: MergeResult,
    *,
    merged_path: Path,
    prompt_manifest_path: Path,
    split_manifest_path: Path,
) -> dict[str, Any]:
    """Describe the actual merged corpus for downstream training gates."""
    counts = _merge_counts(
        result.records,
        list(GENERATORS),
        list(PARTITIONS),
        list(DECODING_IDS),
        list(TOPIC_TAXONOMY),
    )
    return {
        "schema_version": "1.0",
        "generated_at": _now_iso(),
        "config_id": CONFIG_ID,
        "prompt_template_id": PROMPT_TEMPLATE_ID,
        "prompt_manifest": str(prompt_manifest_path),
        "prompt_manifest_sha256": result.prompt_manifest_sha256,
        "split_manifest": str(split_manifest_path),
        "split_digest": result.split_digest,
        "merged": {
            "path": str(merged_path),
            "sha256": result.merged_sha256,
            "rows": len(result.records),
        },
        "generators": {
            spec.generator_id: {
                "model_id": spec.model_id,
                "model_as_served": spec.model_as_served,
                "model_revision": spec.model_revision,
            }
            for spec in GENERATORS
        },
        "composition": {
            "n_rows": len(result.records),
            "n_prompts_with_samples": len(
                {str(record["prompt_id"]) for record in result.records}
            ),
            **counts,
        },
        "coverage": _coverage(result.records, result.prompts),
    }


