"""Merge the frozen E2-C1 API generation shards into one validated corpus.

The three provider runs were generated by separate append-only scripts:

* ``deepseek_v41_flash``  -> ``shards/d*.jsonl``
* ``muse_spark_1_3``      -> ``shards/m*.jsonl`` (``*_p*.jsonl`` are intermediates)
* ``longcat_25``          -> ``shards/g000.jsonl`` .. ``g003.jsonl`` (g004+ was cancelled)

The ``glm_53_flash`` directory name is a leftover from the abandoned GLM plan;
its shards were generated by LongCat 2.5.

The merge is deliberately fail-closed: malformed shard rows, prompt ids absent
from the frozen prompt manifest, unknown decodings, missing split assignments and
duplicate ``(generator_id, prompt_id, decoding_config_id)`` keys are all counted
and never silently admitted.  Failure streams are reported, never merged.

Run ``python -m ml.e2c1.merge_api_shards --dry-run`` to validate and print the
composition without writing anything, or without ``--dry-run`` to write the
corpus, the merge report, the licence registry, the split counts, the corpus
manifest and the decontamination report.
"""

