def _read_bytes(path: Path) -> bytes:
    data = Path(path).read_bytes()
    if data.startswith(b"\xef\xbb\xbf"):
        data = data[3:]
    return data


def _iter_json_lines(data: bytes, path: Path) -> Iterator[tuple[int, dict]]:
    for line_number, raw in enumerate(data.split(b"\n"), start=1):
        if not raw.strip():
            continue
        try:
            obj = json.loads(raw.decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError) as exc:
            raise MergeError(f"{path}:{line_number}: invalid JSON: {exc}") from exc
        if not isinstance(obj, dict):
            raise MergeError(f"{path}:{line_number}: row is not a JSON object")
        yield line_number, obj


def load_prompt_manifest(path: Path) -> tuple[dict[str, dict], str]:
    """Load the frozen prompt manifest, returning ``(by_prompt_id, sha256)``."""
    data = _read_bytes(path)
    prompts: dict[str, dict] = {}
    for line_number, obj in _iter_json_lines(data, Path(path)):
        prompt_id = obj.get("prompt_id")
        if not isinstance(prompt_id, str) or not prompt_id:
            raise MergeError(f"{path}:{line_number}: missing prompt_id")
        if prompt_id in prompts:
            raise MergeError(f"{path}:{line_number}: duplicate prompt_id {prompt_id}")
        for field in ("prompt_hash", "topic_category"):
            if not isinstance(obj.get(field), str) or not obj[field]:
                raise MergeError(
                    f"{path}:{line_number}: missing {field} for {prompt_id}"
                )
        prompts[prompt_id] = obj
    return prompts, hashlib.sha256(data).hexdigest()


def load_split_manifest(path: Path) -> tuple[dict, str]:
    """Load the split manifest and verify its declared digest recomputes."""
    split = json.loads(_read_bytes(path).decode("utf-8"))
    if not isinstance(split, dict):
        raise MergeError(f"{path}: split manifest is not an object")
    assignments = split.get("assignments")
    if not isinstance(assignments, Mapping):
        raise MergeError(f"{path}: split manifest has no assignments object")
    normalized = {str(key): str(value) for key, value in assignments.items()}
    salt = str(split.get("salt", ""))
    computed = e2c1_split_digest(normalized, salt)
    declared = split.get("split_digest")
    if declared is not None and declared != computed:
        raise MergeError(
            f"{path}: split_digest {declared!r} does not recompute ({computed!r})"
        )
    return split, computed


@dataclass(frozen=True)
class LoadedRow:
    path: Path
    line_number: int
    prompt_id: str
    decoding_config_id: str
    text: str

    def as_report(self) -> dict[str, Any]:
        return {
            "file": self.path.name,
            "line": self.line_number,
            "prompt_id": self.prompt_id,
            "decoding_config_id": self.decoding_config_id,
        }


def discover_shard_files(
    shards_root: Path, spec: GeneratorSpec
) -> list[Path]:
    """Return the frozen success shards for one generator.

    Excludes ``*_failures.jsonl`` and any file whose name starts with ``_``.
    Muse intermediate ``*_p*.jsonl`` parts and cancelled ``g004+`` shards are
    excluded by the generator spec.
    """
    directory = Path(shards_root) / spec.shard_dir
    selected: list[Path] = []
    for path in sorted(directory.glob(spec.shard_pattern)):
        name = path.name
        if name.startswith("_") or "_failures" in name:
            continue
        stem = path.stem
        if spec.exclude_intermediate_parts and "_p" in stem:
            continue
        if spec.allowed_stems is not None and stem not in spec.allowed_stems:
            continue
        selected.append(path)
    return selected


def load_generator_rows(
    shards_root: Path, spec: GeneratorSpec
) -> tuple[list[Path], list[LoadedRow]]:
    """Read one generator's success shards, validating the frozen row schema."""
    files = discover_shard_files(shards_root, spec)
    rows: list[LoadedRow] = []
    for path in files:
        for line_number, obj in _iter_json_lines(_read_bytes(path), path):
            keys = frozenset(obj)
            if keys != ROW_KEYS:
                raise MergeError(
                    f"{path}:{line_number}: unexpected row keys {sorted(keys)}"
                )
            prompt_id = obj["prompt_id"]
            decoding = obj["decoding_config_id"]
            text = obj["text"]
            if not all(isinstance(value, str) for value in (prompt_id, decoding, text)):
                raise MergeError(
                    f"{path}:{line_number}: prompt_id/decoding_config_id/text "
                    "must all be strings"
                )
            if not text.strip():
                raise MergeError(f"{path}:{line_number}: empty success text")
            rows.append(
                LoadedRow(
                    path=path,
                    line_number=line_number,
                    prompt_id=prompt_id,
                    decoding_config_id=decoding,
                    text=text,
                )
            )
    return files, rows


def failure_files_for(shard_files: Sequence[Path]) -> list[Path]:
    """The paired ``<stem>_failures.jsonl`` file for each selected success shard."""
    out: list[Path] = []
    for shard in shard_files:
        candidate = shard.with_name(f"{shard.stem}_failures.jsonl")
        if candidate.exists():
            out.append(candidate)
    return out


def scan_failure_files(files: Sequence[Path]) -> dict[str, Any]:
    """Report failure rows by reason.  Failures are never merged."""
    by_reason: collections.Counter[str] = collections.Counter()
    file_rows: list[dict[str, Any]] = []
    total = 0
    for path in files:
        rows = 0
        for line_number, raw in enumerate(_read_bytes(path).split(b"\n"), start=1):
            if not raw.strip():
                continue
            try:
                obj = json.loads(raw.decode("utf-8"))
            except (UnicodeDecodeError, json.JSONDecodeError):
                by_reason["unparsable_failure_row"] += 1
                rows += 1
                continue
            reason = None
            if isinstance(obj, dict):
                reason = obj.get("rejection_reason") or obj.get("reason")
            by_reason[str(reason or "unknown")] += 1
            rows += 1
        total += rows
        file_rows.append({"path": str(path), "rows": rows})
    return {
        "count": total,
        "by_reason": dict(sorted(by_reason.items())),
        "files": file_rows,
    }


