def build_record(
    spec: GeneratorSpec,
    row: LoadedRow,
    prompt: Mapping[str, Any],
    partition: str,
    *,
    config_digest: str = DEFAULT_CONFIG_DIGEST,
    chat_template_sha256: str = DEFAULT_CHAT_TEMPLATE_SHA256,
) -> GenerationRecord:
    """Build one validated :class:`GenerationRecord` from a success row."""
    if row.decoding_config_id not in DECODINGS:
        raise MergeError(
            f"{row.path}:{row.line_number}: unknown decoding "
            f"{row.decoding_config_id!r}"
        )
    decoding = DECODINGS[row.decoding_config_id]
    revision = spec.model_revision
    try:
        return GenerationRecord(
            sample_id=sample_id_for(
                row.prompt_id,
                spec.generator_id,
                revision,
                row.decoding_config_id,
            ),
            prompt_id=row.prompt_id,
            generator_id=spec.generator_id,
            model_id=spec.model_id,
            model_revision=revision,
            licence_ref=spec.generator_id,
            decoding_config_id=row.decoding_config_id,
            temperature=float(decoding["temperature"]),
            top_p=float(decoding["top_p"]),
            max_new_tokens=MAX_NEW_TOKENS,
            seed=SEED,
            batch_index=BATCH_INDEX,
            do_sample=bool(decoding["do_sample"]),
            generated_text=row.text,
            generated_text_hash=sha256_text(row.text),
            generation_timestamp=GENERATION_TIMESTAMP,
            partition=partition,
            topic_category=str(prompt["topic_category"]),
            source_prompt_hash=str(prompt["prompt_hash"]),
            quantisation=dict(QUANTISATION),
            prompt_template_id=PROMPT_TEMPLATE_ID,
            chat_template_sha256=chat_template_sha256,
            config_digest=config_digest,
            finish_reason="unknown",
            quality_flags=list(QUALITY_FLAGS),
        )
    except Exception as exc:  # pydantic ValidationError and friends
        raise MergeError(
            f"{row.path}:{row.line_number}: cannot build record for "
            f"{row.prompt_id}/{spec.generator_id}/{row.decoding_config_id}: {exc}"
        ) from exc


